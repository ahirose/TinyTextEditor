// ============================================================================
// EditManager.cs - 編集操作を担当するクラス
// ============================================================================
//
// 【このファイルの役割】
// - 元に戻す（Undo）/ やり直し（Redo）
// - クリップボード操作（切り取り、コピー、貼り付け）
// - テキスト選択（すべて選択）
//
// 【学習ポイント】
// 1. TextBoxコントロールは Undo/Redo を内蔵している
// 2. クリップボード操作は Clipboard クラスを使う
// 3. 編集操作をMainFormから分離して責務を明確にする
// ============================================================================

namespace TinyTextEditor;

/// <summary>
/// テキストの編集操作を担当するクラス。
/// TextBoxコントロールへの参照を持ち、編集操作を実行する。
/// </summary>
public class EditManager
{
    // ========================================================================
    // フィールド
    // ========================================================================

    /// <summary>
    /// 操作対象のテキストボックス
    /// </summary>
    private readonly TextBox _textBox;

    // ========================================================================
    // コンストラクタ
    // ========================================================================

    /// <summary>
    /// EditManagerのコンストラクタ。
    /// </summary>
    /// <param name="textBox">操作対象のテキストボックス</param>
    public EditManager(TextBox textBox)
    {
        // nullチェック: textBoxがnullなら例外を投げる
        _textBox = textBox ?? throw new ArgumentNullException(nameof(textBox));
    }

    // ========================================================================
    // 元に戻す / やり直し
    // ========================================================================

    /// <summary>
    /// 直前の操作を元に戻す。
    /// TextBoxは標準で1段階のUndoをサポートしている。
    /// </summary>
    public void Undo()
    {
        // CanUndo: 元に戻せる操作があるかどうか
        if (_textBox.CanUndo)
        {
            _textBox.Undo();
        }
    }

    /// <summary>
    /// 元に戻した操作をやり直す。
    /// 注意: TextBoxの標準Undoは1段階なので、Redoは再度Undoを呼ぶ形になる。
    /// </summary>
    public void Redo()
    {
        // TextBoxの標準機能ではRedoは限定的
        // より本格的なUndo/Redoが必要な場合は、自分で履歴を管理する必要がある
        if (_textBox.CanUndo)
        {
            _textBox.Undo();
        }
    }

    // ========================================================================
    // クリップボード操作
    // ========================================================================

    /// <summary>
    /// 選択したテキストを切り取ってクリップボードにコピーする。
    /// 切り取り = コピー + 削除
    /// </summary>
    public void Cut()
    {
        // 何か選択されている場合のみ実行
        if (_textBox.SelectionLength > 0)
        {
            _textBox.Cut();  // TextBoxの標準メソッド
        }
    }

    /// <summary>
    /// 選択したテキストをクリップボードにコピーする。
    /// 元のテキストはそのまま残る。
    /// </summary>
    public void Copy()
    {
        if (_textBox.SelectionLength > 0)
        {
            _textBox.Copy();  // TextBoxの標準メソッド
        }
    }

    /// <summary>
    /// クリップボードのテキストを現在のカーソル位置に貼り付ける。
    /// テキストが選択されている場合は、選択部分を置き換える。
    /// </summary>
    public void Paste()
    {
        // クリップボードにテキストがあるか確認
        if (Clipboard.ContainsText())
        {
            _textBox.Paste();  // TextBoxの標準メソッド
        }
    }

    // ========================================================================
    // 選択操作
    // ========================================================================

    /// <summary>
    /// テキストボックス内のすべてのテキストを選択する。
    /// </summary>
    public void SelectAll()
    {
        _textBox.SelectAll();  // TextBoxの標準メソッド
    }
}

// ============================================================================
// 【補足: より高度なUndo/Redoの実装について】
// ============================================================================
//
// TextBoxの標準Undo機能は1段階しかサポートしていません。
// もし複数段階のUndo/Redoが必要な場合は、以下のような実装が必要です:
//
// 1. 操作履歴を保存するスタック（UndoStack, RedoStack）を用意
// 2. テキストが変更されるたびに、変更前の状態をUndoStackに保存
// 3. Undo実行時: UndoStackから取り出して復元、現在の状態をRedoStackに保存
// 4. Redo実行時: RedoStackから取り出して復元、現在の状態をUndoStackに保存
//
// このテキストエディタでは学習の分かりやすさを優先し、
// TextBoxの標準機能のみを使用しています。
