// - メインウィンドウの起動
//
// 【学習ポイント】
// 1. C#アプリケーションは Main() メソッドから始まる
// 2. Windows Formsアプリケーションは Application クラスで管理される
// 3. フォーム（ウィンドウ）を Application.Run() で起動する
// ============================================================================

namespace TinyTextEditor;

/// <summary>
/// アプリケーションのエントリーポイントを含む静的クラス
/// </summary>
internal static class Program
{
    /// <summary>
    /// アプリケーションのメインエントリーポイント。
    /// プログラムが起動すると、最初にこのメソッドが呼ばれます。
    /// </summary>
    [STAThread]  // Windows Formsに必要な属性（シングルスレッドアパートメント）
    static void Main()
    {
        // ステップ1: 高DPIモードを設定
        // 最近のモニターは高解像度なので、文字がぼやけないように設定
        ApplicationConfiguration.Initialize();

        // ステップ2: メインフォーム（ウィンドウ）を作成して実行
        // Application.Run() はウィンドウが閉じられるまでプログラムを実行し続ける
        Application.Run(new MainForm());

        // ウィンドウが閉じられると、ここに到達してプログラムが終了する
    }
}
